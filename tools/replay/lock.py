#!/usr/bin/env python3
"""Regenerate tools/replay/requirements.lock from the PyPI JSON API.

The lock pins the replay runtime (Unicorn, Capstone, pefile) with the SHA-256 of
every published wheel for 64-bit Linux, macOS and Windows, so `pip install
--require-hashes --only-binary :all:` accepts a wheel on any of them and nothing
else. Run `python3 tools/replay/lock.py` after changing PINNED, then update the
matching constants in crates/biosmod-cli/src/toolchain/replay.rs.

Example: `python3 tools/replay/lock.py --check` exits 1 when the lock is stale.
"""

import argparse
import json
import sys
import urllib.request
from pathlib import Path

PINNED = (("unicorn", "2.1.4"), ("capstone", "5.0.9"), ("pefile", "2024.8.26"))
LOCK = Path(__file__).resolve().with_name("requirements.lock")
HEADER = (
    "# Generated by tools/replay/lock.py from https://pypi.org/pypi/<name>/<version>/json.\n"
    "# Do not edit by hand. Wheels only: 64-bit Linux (glibc and musl), macOS, Windows.\n"
)


def wanted(filename):
    """Whether a wheel file belongs in the lock.

    Example: `wanted("unicorn-2.1.4-cp37-abi3-win_amd64.whl")` is True and
    `wanted("unicorn-2.1.4-py2-none-win_amd64.whl")` is False (a duplicate legacy tag).
    """
    if not filename.endswith(".whl"):
        return False
    tag = filename[: -len(".whl")].split("-", 2)[2]
    if tag.startswith("py2-"):
        return False
    if tag.endswith("-any"):
        return True
    platform = tag.rsplit("-", 1)[1]
    return any(
        key in platform
        for key in ("x86_64", "aarch64", "arm64", "amd64", "universal2")
    )


def render(documents):
    """Render the lock text from `{name: pypi json document}` in PINNED order.

    Example: `render({"pefile": document})` starts with the header and `pefile==...`.
    """
    lines = [HEADER]
    for name, version in PINNED:
        files = documents[name]["urls"]
        hashes = sorted(
            {f["digests"]["sha256"] for f in files if wanted(f["filename"])}
        )
        if not hashes:
            raise SystemExit(
                f"{name}=={version}: expected at least one wheel | received none"
            )
        lines.append(f"{name}=={version} \\\n")
        lines.append(
            " \\\n".join(f"    --hash=sha256:{digest}" for digest in hashes) + "\n"
        )
    return "".join(lines)


def fetch(name, version):
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=60) as response:
        return json.load(response)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail when the lock differs")
    parser.add_argument("--from-dir", type=Path, help="read <name>.json files instead of PyPI")
    args = parser.parse_args(argv)
    documents = {
        name: json.loads((args.from_dir / f"{name}.json").read_text())
        if args.from_dir
        else fetch(name, version)
        for name, version in PINNED
    }
    text = render(documents)
    if args.check:
        if LOCK.read_text() != text:
            print(
                f"{LOCK}: expected the regenerated lock | received a stale file",
                file=sys.stderr,
            )
            return 1
        return 0
    LOCK.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
